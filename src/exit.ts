/**
 * Завершение с кодом выхода — без `process.exit()`.
 *
 * `process.exit()` после сетевого запроса роняет Node на Windows:
 * `Assertion failed: !(handle->flags & UV_HANDLE_CLOSING), file src\win\async.c`,
 * и код выхода становится 127 вместо нашего (живьём 12.11.2026, Node 24.14:
 * отказ Kaiten в `kaiten cancel` — сообщение напечатано, а код чужой; агент и
 * скрипт, которые смотрят на код, видят не то). Воспроизводится любым `fetch`
 * перед `process.exit()`, с таймаутом запроса и без, сразу и через
 * `setImmediate`. Код в `process.exitCode` и обычное завершение — без падения.
 *
 * Поэтому там, где до выхода мог быть запрос, код выставляется здесь, а
 * процесс завершается сам: вызывать последним действием, дальше — только
 * возврат. `process.exit()` остаётся там, где запросов ещё не было (проверка
 * аргументов) или ждать нельзя (читатель вывода ушёл).
 */
export function endWith(code: number): void {
  process.exitCode = code;
}
