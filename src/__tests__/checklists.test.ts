/**
 * Пункты задач → чек-листы Kaiten. Проверяется то, что теряет пункты молча:
 * перенос длинного пункта на следующую строку, пункты в коде, группировка
 * по разделам.
 */
import { describe, expect, it } from 'vitest';

import { extractChecklists } from '../checklists.js';

describe('extractChecklists', () => {
  it('группирует по ближайшему заголовку, склеивает переносы, оставляет ссылку в описании', () => {
    const md = [
      '## Критерии готовности',
      '',
      '- [ ] **В1. Комментарии.** Гость не видит',
      '      внутреннюю заметку',
      '- [x] Второй',
      '',
      '## Шаги (HOW)',
      '',
      '- [ ] 1. Завести аккаунт',
      '  - [ ] вложенный пункт',
      '',
      'Обычный текст',
    ].join('\n');

    const { body, checklists } = extractChecklists(md);

    expect(checklists).toEqual([
      {
        name: 'Агент · Критерии готовности',
        items: [
          { text: '**В1. Комментарии.** Гость не видит внутреннюю заметку', checked: false },
          { text: 'Второй', checked: true },
        ],
      },
      {
        name: 'Агент · Шаги (HOW)',
        items: [
          { text: '1. Завести аккаунт', checked: false },
          { text: 'вложенный пункт', checked: false },
        ],
      },
    ]);
    expect(body).toBe(
      [
        '## Критерии готовности',
        '',
        '_Пункты — в чек-листе «Агент · Критерии готовности» карточки._',
        '',
        '## Шаги (HOW)',
        '',
        '_Пункты — в чек-листе «Агент · Шаги (HOW)» карточки._',
        '',
        'Обычный текст',
      ].join('\n'),
    );
  });

  it('пункты внутри блока кода не трогает', () => {
    const md = ['```md', '- [ ] пример в коде', '```'].join('\n');
    expect(extractChecklists(md)).toEqual({ body: md, checklists: [] });
  });

  it('обычный список не превращает в чек-лист; пункты до заголовков — в чек-лист по умолчанию', () => {
    const md = ['- обычный', '- [X] отмеченный заглавной'].join('\n');
    const { body, checklists } = extractChecklists(md);
    expect(checklists).toEqual([{ name: 'Агент · Чек-лист', items: [{ text: 'отмеченный заглавной', checked: true }] }]);
    expect(body).toBe(['- обычный', '_Пункты — в чек-листе «Агент · Чек-лист» карточки._'].join('\n'));
  });
});
